#!/bin/sh
# Сборка веб-части, которая ляжет ВНУТРЬ Android-приложения (native/www → assets/public).
#
# ЗАЧЕМ. Раньше APK был окном на живой сайт: native/capacitor.config.json задавал
# server.url = https://vahta.razvedchick.ru/vahtahoz.html, а внутри лежала заглушка на
# 340 байт. Следствие — без сети приложение не открывалось ВООБЩЕ: service worker
# в WebView не имеет права перехватывать переход на саму страницу, поэтому офлайн,
# который работает в браузере, обёртке не помогал. Теперь оболочка едет внутри файла.
#
# ЧТО ВАЖНО ЗНАТЬ ПРО АДРЕС. В конфиге вместо server.url стоит
# server.hostname = vahta.razvedchick.ru при androidScheme = https, то есть локальные
# файлы отдаются по ТОМУ ЖЕ адресу, что и сайт раньше. Это не косметика: localStorage,
# сессия входа и кэш привязаны к origin, и смена адреса оставила бы уже установленное
# приложение с пустой базой и разлогином. Менять hostname нельзя.
#
# ЦЕНА. Веб-часть внутри APK застывает на моменте сборки — выкаченная на сайт правка
# сама туда не доедет. Поэтому в оболочку подключается native/packaged.js: он раз в
# сутки спрашивает у сайта номер живой сборки и показывает полоску «вышло обновление».
# Ещё одно следствие: КАЖДЫЙ выпуск веб-части, который должен дойти до людей с APK,
# требует новой сборки APK.
#
# Список файлов — БЕЛЫЙ, как и в scripts/build-site.sh: внутренние документы,
# инфраструктура и бета в приложение не попадают.
set -eu

root=$(cd "$(dirname "$0")/.." && pwd)
out="$root/native/www"

rm -rf "$out"
mkdir -p "$out"

# --- Оболочка ----------------------------------------------------------------
# Кладём под тем же именем, что на сайте: sw.js прекэширует именно "./vahtahoz.html"
# и на нём же держит офлайн-резерв для навигации. Переименуешь — install у SW упадёт.
# Надстройку для APK подключаем перед единственным </body>.
awk '{ sub(/<\/body>/, "<script src=\"./packaged.js\"></script>\n</body>"); print }' \
    "$root/vahtahoz.html" > "$out/vahtahoz.html"

n=$(grep -c 'packaged\.js' "$out/vahtahoz.html" || true)
if [ "$n" != "1" ]; then
  echo "ОШИБКА: надстройка подключилась $n раз(а), ожидалась ровно одна" >&2
  exit 1
fi

# --- Точка входа -------------------------------------------------------------
# Capacitor открывает "/" → index.html. Держать вторую копию оболочки под этим именем
# было бы +900 КБ в файле, поэтому здесь заглушка. Переход мгновенный: он локальный,
# сети не требует.
cat > "$out/index.html" <<'HTML'
<!doctype html>
<meta charset="utf-8">
<title>ВахтаХоз</title>
<script>location.replace("./vahtahoz.html")</script>
HTML

# --- Остальное ---------------------------------------------------------------
# xlsx.js берём внутрь намеренно: выгрузка в Excel должна работать на вахте без сети.
cp "$root/supabase.js"          "$out/supabase.js"
cp "$root/xlsx.js"              "$out/xlsx.js"
cp "$root/manifest.webmanifest" "$out/manifest.webmanifest"
cp "$root/sw.js"                "$out/sw.js"
cp "$root/native/packaged.js"   "$out/packaged.js"

# sw.js внутри APK не лишний, хотя навигацию он там и не перехватывает: он вытесняет
# служебный обработчик, оставшийся от прежних сборок-окон (origin тот же!), который иначе
# продолжал бы подсовывать в приложение старые файлы из своего кэша.

for f in vahtahoz.html index.html supabase.js xlsx.js manifest.webmanifest sw.js packaged.js; do
  [ -s "$out/$f" ] || { echo "ОШИБКА: пустой или отсутствует $f" >&2; exit 1; }
done

echo "Веб-часть приложения собрана в native/www:"
ls -l "$out" | awk 'NR>1 {print $5, $9}'
