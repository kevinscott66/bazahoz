/// Feature flags. Барьер заглушек (geofield-agent-build.md §5) допускает
/// незавершённое ТОЛЬКО за выключенным флагом и с записью в реестр
/// незавершённого — см. geofield/app/UNFINISHED.md.
abstract class AppFeatures {
  /// Транспорт печати на bluetooth-принтер этикеток. В прототипе НЕ реализован
  /// (нет SDK принтера и железа). Рендер бирки — настоящий; передача на принтер —
  /// за этим флагом. Пока выключено — UI честно сообщает «принтер недоступен»,
  /// а не имитирует успешную печать.
  static const bool bluetoothLabelPrinter = false;

  /// Снятие координат с GPS-приёмника. Требует плагина геолокации и разрешений
  /// платформы — подключается на этапе сборки с реальным устройством. Пока
  /// выключено: основной путь — ручной ввод координат (как на десктопе,
  /// ТЗ §11.2), кнопка честно сообщает о недоступности.
  static const bool gpsCapture = false;

  /// «Снять с датчика» для структурных замеров (магнитометр+акселерометр как
  /// компас, с предупреждением о помехах). Требует плагина сенсоров. Пока
  /// выключено: ручной ввод азимута/угла, кнопка честно сообщает.
  static const bool sensorCompass = false;
}
